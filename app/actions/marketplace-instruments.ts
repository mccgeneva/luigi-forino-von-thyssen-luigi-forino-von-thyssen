async function getSessionUser(): Promise<UserProfile | undefined> {
  const session = await resolveCurrentSession()
  return session?.profile
}

async function requireAdmin(passcode: string): Promise<UserProfile> {
  const user = await getSessionUser()
  if (!user) throw new Error("Your session has expired. Please sign in again.")
  if (!(await adminActionAuthorized(passcode))) throw new Error("Administrator authorization failed.")
  return user
}

let ensured = false
async function ensureTable(): Promise<void> {
  if (ensured) return
  await query(
    `CREATE TABLE IF NOT EXISTS marketplace_instruments (
       id                text        PRIMARY KEY,
       isin              text        NOT NULL,
       common_code       text,
       bank_name         text        NOT NULL,
       bank_bic          text        NOT NULL DEFAULT '',
       bank_country      text        NOT NULL DEFAULT '',
       type              text        NOT NULL,
       type_full         text        NOT NULL,
       face_value        numeric     NOT NULL DEFAULT 0,
       currency          text        NOT NULL DEFAULT 'USD',
       tenor_months      integer     NOT NULL DEFAULT 12,
       rating            text        NOT NULL DEFAULT '',
       assignable        boolean     NOT NULL DEFAULT true,
       monetizable       boolean     NOT NULL DEFAULT true,
       available         boolean     NOT NULL DEFAULT true,
       verified_source   text        NOT NULL,
       verified_figi     text,
       verified_name     text,
       verified_at       timestamptz,
       issue_date        date,
       maturity_date     date,
       issuer_details    text,
       beneficiary_terms text,
       delivery_method   text,
       governing_law     text,
       notes             text,
       printout_url      text,
       created_by        text,
       created_at        timestamptz NOT NULL DEFAULT now(),
       updated_at        timestamptz NOT NULL DEFAULT now()
     )`,
  )
  // Backward-compatible additive columns (CUSIP + multi-registry attestations).
  await query(`ALTER TABLE marketplace_instruments ADD COLUMN IF NOT EXISTS cusip text`)
  await query(`ALTER TABLE marketplace_instruments ADD COLUMN IF NOT EXISTS attested_bloomberg timestamptz`)
  await query(`ALTER TABLE marketplace_instruments ADD COLUMN IF NOT EXISTS attested_euroclear timestamptz`)
  await query(`ALTER TABLE marketplace_instruments ADD COLUMN IF NOT EXISTS attested_clearstream timestamptz`)
  await query(`ALTER TABLE marketplace_instruments ADD COLUMN IF NOT EXISTS attested_swift timestamptz`)
  ensured = true
}

function toIso(v: unknown): string | null {
  if (!v) return null
  if (v instanceof Date) return v.toISOString()
  return String(v)
}

function toDateString(v: unknown): string | null {
  if (!v) return null
  if (v instanceof Date) return v.toISOString().slice(0, 10)
  const s = String(v)
  return s.length >= 10 ? s.slice(0, 10) : s
}

function rowToInstrument(row: Record<string, unknown>): MarketplaceInstrument {
  return {
    id: row.id as string,
    isin: row.isin as string,
    cusip: (row.cusip as string | null) ?? null,
    commonCode: (row.common_code as string | null) ?? null,
    bankName: row.bank_name as string,
    bankBic: (row.bank_bic as string) ?? "",
    bankCountry: (row.bank_country as string) ?? "",
    type: row.type as string,
    typeFull: row.type_full as string,
    faceValue: Number(row.face_value),
    currency: row.currency as string,
    tenorMonths: Number(row.tenor_months),
    rating: (row.rating as string) ?? "",
    assignable: row.assignable as boolean,
    monetizable: row.monetizable as boolean,
    available: row.available as boolean,
    verifiedSource: row.verified_source as VerifiedSource,
    verifiedFigi: (row.verified_figi as string | null) ?? null,
    verifiedName: (row.verified_name as string | null) ?? null,
    verifiedAt: (row.verified_at as Date)?.toISOString?.() ?? (row.verified_at as string | null) ?? null,
    verifications: {
      // Fall back to the legacy single-source columns for rows created before
      // per-registry attestation existed, so nothing is mis-reported.
      bloomberg:
        toIso(row.attested_bloomberg) ??
        (row.verified_source === "bloomberg" ? toIso(row.verified_at) : null),
      euroclear:
        toIso(row.attested_euroclear) ??
        (row.verified_source === "euroclear" ? toIso(row.verified_at) : null),
      clearstream:
        toIso(row.attested_clearstream) ??
        (row.verified_source === "clearstream" ? toIso(row.verified_at) : null),
      swift: toIso(row.attested_swift),
    },
    issueDate: toDateString(row.issue_date),
    maturityDate: toDateString(row.maturity_date),
    issuerDetails: (row.issuer_details as string | null) ?? null,
    beneficiaryTerms: (row.beneficiary_terms as string | null) ?? null,
    deliveryMethod: (row.delivery_method as string | null) ?? null,
    governingLaw: (row.governing_law as string | null) ?? null,
    notes: (row.notes as string | null) ?? null,
    printoutUrl: (row.printout_url as string | null) ?? null,
    createdAt: (row.created_at as Date)?.toISOString?.() ?? (row.created_at as string) ?? "",
  }
}

