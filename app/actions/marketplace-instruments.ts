export async function getPublishedInstruments(): Promise<MarketplaceInstrument[]> {
  try {
    await ensureTable()
    const { rows } = await query(
      `SELECT * FROM marketplace_instruments WHERE available = true ORDER BY created_at DESC`,
    )
    return rows.map(rowToInstrument)
  } catch (err) {
    console.log("[v0] getPublishedInstruments failed:", (err as Error).message)
    return []
  }
}

